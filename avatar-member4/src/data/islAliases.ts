export function resolveLexiconSign(gloss: string): ISLSignDefinition | null {
  const normalized = gloss.trim().toUpperCase().replace(/[\s-]+/g, '_');
  if (ISL_LEXICON[normalized]) {
    return ISL_LEXICON[normalized];
  }
  const alias = GLOSS_ALIASES[normalized];
  if (alias && ISL_LEXICON[alias]) {
    return ISL_LEXICON[alias];
  }
  if (ISL_LEXICON[`FS_${normalized}`]) {
    return ISL_LEXICON[`FS_${normalized}`];
  }
  return null;
}

export function getAllAvailableGlosses(): string[] {
  return Object.keys(ISL_LEXICON);
}
